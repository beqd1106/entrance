/**
 * barcode.js - 会員番号のバーコード（Code128-B）をSVGで描く
 *
 * 店頭でスタッフが読み取れるように、会員証に載せる。
 * 外部ライブラリを入れない方針なので、規格どおりの本数分だけ自前で並べる。
 *
 * Code128 の決まりごと
 *   - 1文字は11モジュール（黒と白の帯を3本ずつ）で表す
 *   - 先頭にスタート記号（Bコードは 104）、末尾にチェック記号とストップ記号
 *   - チェック記号 =（スタート値 + Σ(位置 × 文字値)）を 103 で割った余り
 *   - ストップ記号だけは13モジュール
 */

/**
 * 各記号のモジュール幅。1文字あたり6つの数字が
 * 「黒・白・黒・白・黒・白」の順の帯の太さを表す（合計11）。
 * 添字がそのまま Code128 の文字値になる。
 */
const PATTERNS = [
  '212222', '222122', '222221', '121223', '121322', '131222', '122213', '122312',
  '132212', '221213', '221312', '231212', '112232', '122132', '122231', '113222',
  '123122', '123221', '223211', '221132', '221231', '213212', '223112', '312131',
  '311222', '321122', '321221', '312212', '322112', '322211', '212123', '212321',
  '232121', '111323', '131123', '131321', '112313', '132113', '132311', '211313',
  '231113', '231311', '112133', '112331', '132131', '113123', '113321', '133121',
  '313121', '211331', '231131', '213113', '213311', '213131', '311123', '311321',
  '331121', '312113', '312311', '332111', '314111', '221411', '431111', '111224',
  '111422', '121124', '121421', '141122', '141221', '112214', '112412', '122114',
  '122411', '142112', '142211', '241211', '221114', '413111', '241112', '134111',
  '111242', '121142', '121241', '114212', '124112', '124211', '411212', '421112',
  '421211', '212141', '214121', '412121', '111143', '111341', '131141', '114113',
  '114311', '411113', '411311', '113141', '114131', '311141', '411131', '211412',
  '211214', '211232', '233111',
];
const START_B = 104;
const STOP = '2331112';   // ストップ記号だけ13モジュール（帯が7本）

/** Code128-B が扱えるのは ASCII 32〜126 */
function encodable(text) {
  return String(text).split('').filter((c) => {
    const n = c.charCodeAt(0);
    return n >= 32 && n <= 126;
  }).join('');
}

/**
 * バーコードのSVGを返す。
 * @param {string} text 会員番号など
 * @param {{height?:number, module?:number, quiet?:number}} opts
 */
export function barcodeSVG(text, opts = {}) {
  const src = encodable(text);
  if (!src) return '';
  const module = opts.module || 2;      // 細い帯1本の太さ
  const height = opts.height || 64;
  const quiet = opts.quiet ?? 10;       // 左右の余白（規格では10モジュール以上）

  // スタート → データ → チェック → ストップ
  const values = [START_B, ...src.split('').map((c) => c.charCodeAt(0) - 32)];
  let sum = START_B;
  for (let i = 1; i < values.length; i++) sum += values[i] * i;
  values.push(sum % 103);
  const widths = values.map((v) => PATTERNS[v]).join('') + STOP;

  // 帯を左から並べる。奇数番目が黒、偶数番目が白
  let x = quiet * module;
  let bars = '';
  for (let i = 0; i < widths.length; i++) {
    const w = Number(widths[i]) * module;
    if (i % 2 === 0) bars += `<rect x="${x}" y="0" width="${w}" height="${height}"/>`;
    x += w;
  }
  const total = x + quiet * module;
  return `<svg viewBox="0 0 ${total} ${height}" width="100%" height="${height}"`
    + ` preserveAspectRatio="xMidYMid meet" role="img" aria-label="会員番号 ${src}">`
    + `<rect x="0" y="0" width="${total}" height="${height}" fill="#fff"/>`
    + `<g fill="#111">${bars}</g></svg>`;
}
