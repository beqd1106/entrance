// ---------------------------------------------------------------------------
// 索子（竹）
// ---------------------------------------------------------------------------
/**
 * 竹1本。
 *
 * 以前は「中央がくびれ、上下に節がある」実物どおりの形にしていたが、
 * 小さく表示すると細い胴が消えて上下の節だけが残り、H の字のように見えていた。
 * ここでは太い縦棒を1本の塊として置き、面の色で節を2本抜く。
 * 塊なので縮んでも消えず、抜きが残るので竹だと分かる。
 */
function bamboo(x, y, h, cls = 'green') {
  const f = (v) => Number(v).toFixed(1);
  const w = h * 0.42;                        // 竹の太さ
  const top = y - h / 2;
  // 節の抜きは細くする。太いと竹が分断されて「だんごの串」に見える
  const nodeH = Math.max(1.2, h * 0.045);
  const body = `<rect x="${f(x - w / 2)}" y="${f(top)}" width="${f(w)}" height="${f(h)}"`
    + ` rx="${f(w * 0.3)}"/>`;
  const node = (cy) => `<rect x="${f(x - w / 2)}" y="${f(cy - nodeH / 2)}" width="${f(w)}"`
    + ` height="${f(nodeH)}" class="face"/>`;
  // 節の抜きは、竹そのものが細くなる小さい牌では省く
  const nodes = h >= 26 ? node(top + h * 0.3) + node(top + h * 0.7) : '';
  // 竹に縦の光を入れると、竹が縦に割れて2本に見えてしまう。
  // 塊のまま置き、節の抜きだけで竹らしさを出す。
  return `<g class="${cls}">${body}</g>${nodes}`;
}

/**
 * 一索は鳥（孔雀）。
 * 細い線は小さくすると消えるので、頭・胴・尾・冠羽をそれぞれ
 * ひとつの塊として描き、輪郭のすき間で形を読ませる。
 */
function bird() {
  return `<svg ${VB}>`
    // 尾（下へ大きく流れる羽）
    + `<path d="M44 92 C40 114 32 128 20 138 C40 134 54 120 60 100Z" class="green"/>`
    + `<path d="M56 96 C58 116 54 130 46 140 C62 134 70 118 70 100Z" class="red"/>`
    // 胴（大きな塊）
    + `<path d="M50 42 C70 46 80 66 74 90 C69 110 54 116 44 106 C32 94 32 58 50 42Z" class="green"/>`
    // 胸の抜き（胴と頭を切り分ける）
    + `<path d="M52 60 C44 70 44 90 52 100 C59 91 59 69 52 60Z" class="face"/>`
    // 頭
    + `<circle cx="45" cy="33" r="15" class="green"/>`
    + `<circle cx="41" cy="30" r="4.2" class="face"/>`
    // くちばし
    + `<path d="M31 35 L14 41 L32 46Z" class="red"/>`
    // 冠羽
    + `<path d="M50 18 C46 9 51 3 59 4 C60 12 56 18 51 21Z" class="red"/>`
    + `<path d="M60 23 C61 14 67 10 73 12 C71 20 67 25 61 27Z" class="green"/>`
    + `</svg>`;
}

