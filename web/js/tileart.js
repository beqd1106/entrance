/**
 * tileart.js - 牌面のインラインSVG
 *
 * 外部画像・フォントに依存せず、牌の絵柄をベクターで描く。
 * 色は semantic class（ink / red / green / blue）で塗り分け、
 * 赤牌・金牌などの属性は CSS 側で class を上書きして表現する。
 *
 * viewBox は 0 0 100 140（牌の面）に統一。
 *
 * 描き方の方針（天鳳・雀魂・麻雀一番街の牌面を参考にしている）：
 *   - 25px 角まで縮んでも「何の牌か」が分かることを最優先にする。
 *     細い線・小さな抜きは潰れるので、塊で描いて余白で区切る。
 *   - 筒子は輪を太く、索子は竹を太い縦棒にして、数を数えやすくする。
 *   - 萬子は漢数字を主役にし、「萬」は下に小さく添える。
 */

const VB = 'viewBox="0 0 100 140"';

// ---------------------------------------------------------------------------
// 筒子（輪）
// ---------------------------------------------------------------------------
/**
 * 筒子の輪ひとつ。
 * 外周の輪を太く、芯をはっきり残す。小さく表示したときに
 * 「輪の集まり」ではなく「ただの点」に見えてしまうのを防ぐ。
 */
function pin(x, y, r, cls = 'blue') {
  const core = cls === 'blue' ? 'red' : cls;
  const f = (v) => Number(v).toFixed(2);
  // 内側の白をわずかに上へずらすと、平らな輪ではなく丸みのある牌に見える
  return `<circle cx="${x}" cy="${y}" r="${f(r)}" class="${cls}"/>`
    + `<circle cx="${x}" cy="${f(y - r * 0.05)}" r="${f(r * 0.58)}" class="face"/>`
    + `<circle cx="${x}" cy="${y}" r="${f(r * 0.34)}" class="${core}"/>`;
}

