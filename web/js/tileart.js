// ---------------------------------------------------------------------------
// 萬子・字牌・花牌（文字）
// ---------------------------------------------------------------------------
const KANJI = ['一', '二', '三', '四', '五', '六', '七', '八', '九'];

/**
 * 萬子は漢数字が主役。
 * 以前は「一」と「萬」をほぼ同じ大きさで2段に積んでいたため、
 * 小さくするとどちらも潰れて読めなかった。
 * 数字を大きく、「萬」は下に小さく添える形にする。
 */
function manzu(n) {
  return `<svg ${VB}>`
    + `<text x="50" y="66" class="glyph ink" font-size="64">${KANJI[n - 1]}</text>`
    + `<text x="50" y="128" class="glyph red" font-size="44">萬</text>`
    + `</svg>`;
}

function honor(t) {
  // 27:東 28:南 29:西 30:北 31:白 32:發 33:中
  if (t === 31) {
    // 白は絵柄なし（真っ白）。白ポッチの赤い点だけがCSS側で乗る
    return `<svg ${VB}></svg>`;
  }
  const ch = ['東', '南', '西', '北', '白', '發', '中'][t - 27];
  const cls = t === 33 ? 'red' : t === 32 ? 'green' : 'ink';
  return `<svg ${VB}><text x="50" y="101" class="glyph ${cls}" font-size="84">${ch}</text></svg>`;
}

function flower(t) {
  const ch = ['春', '夏', '秋', '冬'][t - 34];
  const cls = ['green', 'red', 'gold-ink', 'blue'][t - 34];
  return `<svg ${VB}><text x="50" y="99" class="glyph ${cls}" font-size="76">${ch}</text></svg>`;
}

// ---------------------------------------------------------------------------
export function tileFaceSVG(t) {
  if (t >= 34) return flower(t);
  if (t >= 27) return honor(t);
  const n = (t % 9) + 1;
  if (t < 9) return manzu(n);
  if (t < 18) return pinzu(n);
  return souzu(n);
}

